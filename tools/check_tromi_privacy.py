#!/usr/bin/env python3
"""
Check the Tromi privacy policy pages before committing an edit to them:
tromi/privacy.html (English) and tromi/privacy-fr.html (French). Changes nothing.

These two pages are the policy's source: edit them here, by hand. Until 2026-11-23 they were
generated by tools/publish_privacy_page.py in the Tromi repo from its docs/PRIVACY_POLICY*.md;
that script and those files are gone, and this check keeps the guard the script had.

1. The French page mirrors the English one, block for block: the same sequence of headings,
   paragraphs, list items and table rows (with the same number of cells), so an English edit
   can't be committed without its translation.
2. The "Last updated" / "Dernière mise à jour" lines carry the same date.
3. Every paragraph, heading, list, table and cell that opens also closes, in order.
4. No Markdown is left in the text (** or ` or [text](url)): the pages are HTML, so write
   <strong>, <code> and <a>.

Usage: tools/check_tromi_privacy.py [EN_PAGE FR_PAGE]
Exit status 0 when both pages pass, 1 with the first problem found.
"""
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

SITE_DIR = Path(__file__).resolve().parent.parent

MONTHS = {
    "en": ["January", "February", "March", "April", "May", "June", "July",
           "August", "September", "October", "November", "December"],
    "fr": ["janvier", "février", "mars", "avril", "mai", "juin", "juillet",
           "août", "septembre", "octobre", "novembre", "décembre"],
}
UPDATED = {
    "en": re.compile(r"Last updated: (?P<month>[A-Z][a-z]+) (?P<day>\d{1,2}), (?P<year>\d{4})"),
    "fr": re.compile(r"Dernière mise à jour : (?P<day>1er|\d{1,2}) (?P<month>[a-zéû]+) (?P<year>\d{4})"),
}
# The blocks the policy is made of, compared between the two pages.
BLOCKS = {"h1", "h2", "h3", "p", "li", "tr"}
# The tags that must open and close in order.
PAIRED = BLOCKS | {"ul", "table", "th", "td", "nav", "strong", "code", "a"}
MARKDOWN = re.compile(r"\*\*|`|\[[^\]]*\]\(")


class Page(HTMLParser):
    def __init__(self, path):
        super().__init__(convert_charrefs=True)
        self.path = path
        self.blocks = []  # [(kind, line, text)], a tr's kind carrying its cell count
        self.stack = []
        self.in_body = self.in_nav = False
        self.current = None
        self.cells = 0
        self.problem = None
        self.feed(path.read_text(encoding="utf-8"))
        self.close()
        if self.stack and not self.problem:
            self.fail(f"<{self.stack[-1][0]}> opened on line {self.stack[-1][1]} never closes")

    def fail(self, message):
        if not self.problem:
            self.problem = f"{self.path.name}:{self.getpos()[0]}: {message}"

    def handle_starttag(self, tag, attrs):
        if tag == "body":
            self.in_body = True
        if not self.in_body:
            return
        if tag in PAIRED:
            self.stack.append((tag, self.getpos()[0]))
        if tag == "nav":
            self.in_nav = True
        elif tag in BLOCKS and not self.in_nav:
            if self.current and tag != "tr":
                self.fail(f"<{tag}> inside <{self.current[0]}>")
            self.current = [tag, self.getpos()[0], ""]
            self.cells = 0
        elif tag in ("th", "td"):
            self.cells += 1

    def handle_endtag(self, tag):
        if not self.in_body or tag not in PAIRED:
            return
        if not self.stack or self.stack[-1][0] != tag:
            opened = f"<{self.stack[-1][0]}> from line {self.stack[-1][1]}" if self.stack else "nothing"
            self.fail(f"</{tag}> closes {opened}")
            return
        self.stack.pop()
        if tag == "nav":
            self.in_nav = False
        elif self.current and tag == self.current[0]:
            kind, line, text = self.current
            if kind == "tr":
                kind = f"tr/{self.cells}"
            text = " ".join(text.split())
            if MARKDOWN.search(text):
                self.fail(f"Markdown left in the text: {text[:80]}")
            self.blocks.append((kind, line, text))
            self.current = None

    def handle_data(self, data):
        if self.current:
            self.current[2] += data


def updated_on(lang, page):
    for kind, line, text in page.blocks:
        if kind == "p" and text.startswith(("Last updated", "Dernière mise à jour")):
            m = UPDATED[lang].fullmatch(text)
            if not m or m["month"] not in MONTHS[lang]:
                sys.exit(f"{page.path.name}:{line}: unreadable date: {text}")
            day = 1 if m["day"] == "1er" else int(m["day"])
            return f"{m['year']}-{MONTHS[lang].index(m['month']) + 1:02d}-{day:02d}"
    sys.exit(f"{page.path.name}: no last-updated line")


def main():
    if len(sys.argv) not in (1, 3):
        sys.exit(__doc__.strip().splitlines()[-2])
    paths = [Path(p) for p in sys.argv[1:]] or [SITE_DIR / "tromi/privacy.html", SITE_DIR / "tromi/privacy-fr.html"]
    en, fr = Page(paths[0]), Page(paths[1])
    for page in (en, fr):
        if page.problem:
            sys.exit(page.problem)
    for (en_kind, en_line, _), (fr_kind, fr_line, _) in zip(en.blocks, fr.blocks):
        if en_kind != fr_kind:
            sys.exit(f"The French page no longer mirrors the English one: {en.path.name}:{en_line} is {en_kind}, "
                     f"{fr.path.name}:{fr_line} is {fr_kind}. Translate the change into both pages.")
    if len(en.blocks) != len(fr.blocks):
        sys.exit(f"The French page no longer mirrors the English one: {len(en.blocks)} blocks in {en.path.name}, "
                 f"{len(fr.blocks)} in {fr.path.name}. Translate the change into both pages.")
    en_date, fr_date = updated_on("en", en), updated_on("fr", fr)
    if en_date != fr_date:
        sys.exit(f"Last-updated dates differ: {en_date} in {en.path.name}, {fr_date} in {fr.path.name}. "
                 "An English edit needs its French translation, with the same date.")
    print(f"OK: {len(en.blocks)} blocks in each page, both dated {en_date}.")


if __name__ == "__main__":
    main()
